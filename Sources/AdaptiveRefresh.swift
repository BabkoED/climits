import Foundation

// Как часто спрашивать лимиты, когда частоту выбирает приложение.
//
// ЗАЧЕМ. Фиксированный интервал плох с обеих сторон сразу: когда человек
// смотрит в меню и работает, пять минут - долго, а ночью те же пять
// минут - это сотня лишних запросов к эндпоинту, который и так огрызается
// 429. Приём из CodexBar (AdaptiveRefreshPolicy, MIT): частота следует за
// тем, смотрит ли человек и идёт ли работа.
//
// Чистая функция: ни часов, ни ProcessInfo внутри. Всё, что зависит от
// машины, приходит во входе - иначе таблицу ниже не проверить тестом.
//
// ОТЛИЧИЕ ОТ CodexBar - потолок 15 минут, а не 30. Лимит общий на аккаунт
// и тратится с телефона и из браузера, а этого по сессиям на машинах не
// видно вовсе. Полчаса «простоя» по нашим признакам могут быть полчаса
// работы в приложении Claude - и процент в строке отставал бы на столько же.
enum AdaptiveRefresh {
    struct Input {
        var now: Date
        var lastMenuOpen: Date?
        var busySessions: Bool     // есть сессия, которая работает прямо сейчас
        var constrained: Bool      // энергосбережение или перегрев
    }

    enum Reason: String {
        case constrained, looking, warm, working, idle
    }

    static let fastest: TimeInterval = 120
    static let slowest: TimeInterval = 900

    static func next(_ i: Input) -> (delay: TimeInterval, reason: Reason) {
        if i.constrained { return (slowest, .constrained) }
        // Время открытия из будущего (перевели часы) считаем «только что»:
        // иначе отрицательная разница провалилась бы в самый медленный ряд.
        let since = i.lastMenuOpen.map { max(0, i.now.timeIntervalSince($0)) }
        if let s = since, s <= 5 * 60 { return (fastest, .looking) }
        if let s = since, s <= 60 * 60 { return (300, .warm) }
        if i.busySessions { return (300, .working) }
        return (slowest, .idle)
    }
}

// Сказать, когда лимит снова есть.
//
// ЗАЧЕМ. Предупреждение «лимит на исходе» отвечает на половину вопроса
// «работать дальше или подождать». Вторая половина - «когда можно снова» -
// до сих пор требовала держать в голове время сброса и заглядывать в трей.
// У CodexBar на это конфетти при недельном сбросе; нам полезнее тихое
// сообщение, и только там, где человек перед этим упирался.
//
// Поэтому сообщение ставится В МОМЕНТ предупреждения и на время сброса:
// система доставит его сама, даже если приложение в этот момент спит или
// опрос ушёл на пятнадцать минут. Один идентификатор на лимит - повторная
// постановка заменяет прежнюю, а не добавляет вторую.
enum ResetNotice {
    static func id(_ key: String) -> String { return "reset." + key }

    // Через сколько секунд сказать. nil - говорить нечего: сброс неизвестен
    // или уже прошёл (тогда сообщение пришло бы сразу и соврало бы).
    static func delay(resetsAt: Date?, now: Date = Date()) -> TimeInterval? {
        guard let r = resetsAt else { return nil }
        let d = r.timeIntervalSince(now)
        // Минута запаса: сервер сбрасывает окно не в ту же секунду, что
        // написано, и сообщение «уже можно» раньше сброса хуже опоздавшего.
        return d > 30 ? d + 60 : nil
    }

    // Лимит окна, которое сбросится, и остальные лимиты - для проверки,
    // можно ли будет работать на самом деле.
    struct Window {
        let key: String
        let pct: Int
        let resetsAt: Date?
        let isModel: Bool
    }

    // Что мешает сказать «можно работать» после сброса этого окна.
    //
    // Найдено ревью 24.09.2026: неделя на 100%, пятичасовое окно перешло
    // порог - через несколько часов приходит «можно работать», а нельзя:
    // неделя всё ещё выбрана. Мешает только ОБЩИЙ лимит, упёршийся до
    // более позднего сброса. Лимит по модели не мешает: Opus на 100% -
    // это «работай на другой модели», а не «жди».
    static func blocked(_ w: Window, among all: [Window]) -> Bool {
        guard let r = w.resetsAt else { return true }
        return all.contains { o in
            o.key != w.key && !o.isModel && o.pct >= 100
                && (o.resetsAt ?? .distantFuture) > r.addingTimeInterval(60)
        }
    }

    // Снимать ли поставленное сообщение, когда окно сменилось.
    //
    // Штатный сброс - время старого окна прошло: сообщение уже доставлено
    // или вот-вот будет (оно стоит на минуту позже сброса), и снять его
    // в эту минуту значило бы украсть его у человека. Снимаем, только
    // если старое окно кончилось ДОСРОЧНО - его время ещё впереди.
    static func stale(oldStamp: String?, now: Date = Date()) -> Bool {
        guard let s = oldStamp, let t = Double(s) else { return false }
        return Date(timeIntervalSince1970: t) > now
    }

    static func text(long: String) -> (title: String, body: String) {
        return (L("Лимит снова есть", "Limit is back"),
                // «5-часовое окно: окно сбросилось» повторяло бы слово,
                // а «Неделя, всего сбросилось» не склеивается вовсе.
                L("\(long): снова с нуля, можно работать",
                  "\(long): back to zero, you can work"))
    }
}
