import AppKit

// Кружок в строке меню - кольцом, а не знаком.
//
// ЗАЧЕМ. Кружок отвечает на «стоит ли заглянуть в меню» и до этой правки
// был одним из трёх знаков (◔ ◑ ◕): три ступени на сто процентов. То есть
// 34% и 79% выглядели одинаково, и всю работу делал цвет. Нарисованное
// кольцо несёт процент дугой - непрерывно, в габарите того же одного знака.
// Строка меню - самое дорогое место в приложении, и это единственный
// способ сказать в ней больше, не заняв ни одного знака.
//
// ЧТО НЕ ИЗМЕНИЛОСЬ, и это намеренно:
//   * кольцо показывает САМЫЙ нагруженный лимит - тот же, что показывал
//     знак. Носитель другой, сигнал тот же;
//   * цвет берётся из Palette.titleColor, то есть пока всё спокойно
//     кольцо нейтральное. Постоянный цвет в строке меню перестаёт
//     читаться как сигнал на второй день - это уже было решено, и
//     кольцо не повод решать заново.
//
// ПОЧЕМУ КАРТИНКОЙ У КНОПКИ, А НЕ ВЛОЖЕНИЕМ В СТРОКУ. Вложение (как
// CapsuleBar в строках меню) позволило бы поставить кольцо в любое место
// шаблона. Но attributedTitle у кнопки трея рисуется не тем же путём, что
// заголовок пункта меню, и проверить это отсюда нечем - Мака нет. Картинка
// у кнопки - документированный путь для статус-элемента, он либо работает,
// либо виден сразу. Цена: кольцо может стоять только по краям строки,
// а не в середине. Для трёх-четырёх знаков это не ограничение.
enum RingBar {

    // Прозрачный отступ с той стороны, где стоят цифры. Своего зазора
    // между картинкой и заголовком AppKit не даёт настраивать, поэтому
    // он нарисован внутри картинки.
    // badge - точка в правом верхнем углу кольца: сбой у Anthropic.
    // Приём CodexBar (значок статуса поверх индикатора). Точка, а не знак
    // в тексте: места в строке меню нет, а сигнал «это не у тебя» должен
    // быть виден, не открывая меню.
    static func image(percent: Int, color: NSColor, font: NSFont,
                      trailing: Bool = false, badge: NSColor? = nil) -> NSImage {
        let d = CGFloat(Layout.ringDiameter(capHeight: Double(font.capHeight)))
        let stroke = CGFloat(Layout.ringStroke(diameter: Double(d)))
        let gap = CGFloat(Layout.ringGap)
        let size = NSSize(width: d + gap, height: d)

        let img = NSImage(size: size, flipped: false) { _ in
            // Обод рисуется по средней линии, поэтому радиус меньше на
            // половину толщины: иначе половина обода уходит за край
            // картинки и срезается.
            let originX = trailing ? gap : 0
            let center = NSPoint(x: originX + d / 2, y: d / 2)
            let r = (d - stroke) / 2

            // Подложка - тот же цвет, приглушённый, а не серый: пустая
            // часть принадлежит этому же кольцу, и в тёмной теме не
            // спорит с фоном. Тот же приём, что у капсулы в меню.
            let track = NSBezierPath()
            track.appendArc(withCenter: center, radius: r,
                            startAngle: 0, endAngle: 360)
            track.lineWidth = stroke
            color.withAlphaComponent(0.22).setStroke()
            track.stroke()

            let sweep = CGFloat(Layout.ringSweep(pct: percent))
            if sweep > 0 {
                // От двенадцати часов по часовой стрелке: так же читается
                // заполнение циферблата, и так же растёт полоска слева
                // направо. Против часовой то же число выглядит как остаток.
                let arc = NSBezierPath()
                arc.appendArc(withCenter: center, radius: r,
                              startAngle: 90, endAngle: 90 - sweep,
                              clockwise: true)
                arc.lineWidth = stroke
                // Торцы ПРЯМЫЕ, а не круглые.
                //
                // Круглый торец удлиняет дугу на половину толщины с каждого
                // конца. Замер по снимку из CI: при обводе 2.4 это ~9° на
                // торец, то есть 92% рисовались почти сомкнутым кольцом и
                // читались как 100%. Врёт эта прибавка ровно там, где
                // цифра важнее всего - у верхнего края. Прямой торец
                // отдаёт ровно тот угол, который посчитан.
                arc.lineCapStyle = .butt
                color.setStroke()
                arc.stroke()
            }
            if let b = badge {
                // Треть диаметра: меньше не видно на обычном экране, больше
                // закрывает то самое кольцо, ради которого значок и стоит.
                let dot = max(4, (d * 0.38).rounded())
                let rect = NSRect(x: originX + d - dot, y: d - dot, width: dot, height: dot)
                // Вырез под точку - фоном строки меню нельзя (он у каждого
                // свой), поэтому кольцо под точкой стирается прозрачностью.
                NSGraphicsContext.current?.compositingOperation = .clear
                NSBezierPath(ovalIn: rect.insetBy(dx: -1, dy: -1)).fill()
                NSGraphicsContext.current?.compositingOperation = .sourceOver
                b.setFill()
                NSBezierPath(ovalIn: rect).fill()
            }
            return true
        }
        // Не шаблон: шаблонную картинку система перекрашивает в цвет текста,
        // и цвет по нагрузке пропал бы вместе с сигналом.
        img.isTemplate = false
        // accessibilityDescription у NSImage здесь НЕ ставится намеренно.
        // Проверить этот вызов с Linux нечем, а правило репозитория -
        // брать вызовы AppKit знак в знак из того, что уже зелено в CI.
        // Читалка экрана и так получает процент: он стоит в заголовке
        // кнопки словами, кольцо его только повторяет.
        return img
    }
}
